// остальной интерфейс: русская строка — ключ словаря, перевод лежит рядом.
//
// Списки собираются функциями, а не константами: `tr()` обязан посмотреть на
// язык, выбранный сейчас, иначе после смены языка экран остался бы со старыми
// строками.

